def dashboard_page():

    st.title("🏠 Dashboard")

    st.caption(
        f"Welcome, {st.session_state.user_name}"
    )

    clients = get_clients()

    today = date.today().isoformat()

    # --------------------------------------------------------
    # KPI CALCULATIONS
    # --------------------------------------------------------

    total_clients = len(clients)

    conn = get_connection()

    cursor = conn.cursor()

    cursor.execute(adapt_sql("""
        SELECT COUNT(*)
        FROM call_history
        WHERE DATE(call_datetime) = ?
    """), (today,))

    calls_today = cursor.fetchone()[0]

    cursor.execute(adapt_sql("""
        SELECT COUNT(*)
        FROM clients
        WHERE next_followup_date = ?
    """), (today,))

    due_followups = cursor.fetchone()[0]

    cursor.execute(adapt_sql("""
        SELECT COUNT(*)
        FROM clients
        WHERE next_followup_date < ?
    """), (today,))

    overdue = cursor.fetchone()[0]

    conn.close()

    # --------------------------------------------------------
    # KPI CARDS
    # --------------------------------------------------------

