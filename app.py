def get_database_url():
    """Read the hosted database URL from environment or Streamlit secrets."""
    url = os.getenv("DATABASE_URL", "").strip()
    if not url:
        try:
            url = str(st.secrets.get("DATABASE_URL", "")).strip()
        except Exception:
            url = ""
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://"):]
    return url


def is_postgres():
    return get_database_url().startswith(("postgresql://", "postgresql+psycopg2://"))


def get_connection():
    """Use PostgreSQL in the cloud and SQLite for local development."""
    if is_postgres():
        import psycopg2
        return psycopg2.connect(get_database_url())
    return sqlite3.connect(DB_NAME)


def adapt_sql(sql):
    """Translate SQLite-style placeholders to PostgreSQL placeholders."""
    return sql.replace("?", "%s") if is_postgres() else sql


def read_sql_query(sql, conn, params=None):
    """Run a dataframe query on either supported database backend."""
    return pd.read_sql_query(adapt_sql(sql), conn, params=params)


def initialize_database():
    conn = get_connection()
    cursor = conn.cursor()
    if is_postgres():
        cursor.execute(adapt_sql("""
            CREATE TABLE IF NOT EXISTS clients (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                client_name TEXT NOT NULL,
                contact_number TEXT,
                address TEXT,
                area TEXT,
                city TEXT,
                email TEXT,
                client_type TEXT,
                client_label TEXT,
                last_followup_date TEXT,
                next_followup_date TEXT,
                created_at TEXT,
                created_by TEXT
            )
        """))
        cursor.execute(adapt_sql("""
            CREATE TABLE IF NOT EXISTS call_history (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                client_id BIGINT REFERENCES clients(id),
                call_datetime TEXT,
                call_status TEXT,
                interest TEXT,
                order_status TEXT,
                next_followup_date TEXT,
                next_followup_time TEXT,
                comments TEXT,
                called_by TEXT,
                call_number INTEGER
            )
        """))
    else:
        cursor.execute(adapt_sql("""
            CREATE TABLE IF NOT EXISTS clients (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                client_name TEXT NOT NULL,
                contact_number TEXT,
                address TEXT,
                area TEXT,
                city TEXT,
                email TEXT,
                client_type TEXT,
                client_label TEXT,
                last_followup_date TEXT,
                next_followup_date TEXT,
                created_at TEXT,
                created_by TEXT
            )
        """))
        cursor.execute(adapt_sql("""
            CREATE TABLE IF NOT EXISTS call_history (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                client_id INTEGER,
                call_datetime TEXT,
                call_status TEXT,
                interest TEXT,
                order_status TEXT,
                next_followup_date TEXT,
                next_followup_time TEXT,
                comments TEXT,
                called_by TEXT,
                call_number INTEGER,
                FOREIGN KEY (client_id) REFERENCES clients(id)
            )
        """))
    conn.commit()
    conn.close()


