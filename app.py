def reports_page():

    st.title("📊 Reports")

    conn = get_connection()

    calls = read_sql_query("""
        SELECT
            ch.*,
            c.client_name,
            c.contact_number,
            c.city,
            c.area,
            c.client_type,
            c.client_label
        FROM call_history ch
        LEFT JOIN clients c
            ON ch.client_id = c.id
        ORDER BY ch.call_datetime DESC
    """, conn)

    conn.close()

    if calls.empty:

        st.info(
            "No calling data available for reports."
        )

        return

    # --------------------------------------------------------
    # FILTERS
    # --------------------------------------------------------

    st.subheader("🔎 Report Filters")

    col1, col2, col3, col4 = st.columns(4)

    with col1:

        type_filter = st.selectbox(
            "Client Type",
            ["All"] +
            sorted(
                calls["client_type"]
                .dropna()
                .unique()
                .tolist()
            )
        )

    with col2:

        call_filter = st.selectbox(
            "Call Status",
            ["All"] +
            sorted(
                calls["call_status"]
                .dropna()
                .unique()
                .tolist()
            )
        )

    with col3:

        interest_filter = st.selectbox(
            "Interest",
            ["All"] +
            sorted(
                calls["interest"]
                .dropna()
                .unique()
                .tolist()
            )
        )

    with col4:

        order_filter = st.selectbox(
            "Order Status",
            ["All"] +
            sorted(
                calls["order_status"]
                .dropna()
                .unique()
                .tolist()
            )
        )

    # --------------------------------------------------------
    # APPLY FILTERS
    # --------------------------------------------------------

    filtered = calls.copy()

    if type_filter != "All":

        filtered = filtered[
            filtered["client_type"] == type_filter
        ]

    if call_filter != "All":

        filtered = filtered[
            filtered["call_status"] == call_filter
        ]

    if interest_filter != "All":

        filtered = filtered[
            filtered["interest"] == interest_filter
        ]

    if order_filter != "All":

        filtered = filtered[
            filtered["order_status"] == order_filter
        ]

    # --------------------------------------------------------
    # DATE FILTER
    # --------------------------------------------------------

    col1, col2 = st.columns(2)

    with col1:

        start_date = st.date_input(
            "Start Date",
            value=date.today() - timedelta(days=30)
        )

    with col2:

        end_date = st.date_input(
            "End Date",
            value=date.today()
        )

    filtered["call_date"] = pd.to_datetime(
        filtered["call_datetime"],
        errors="coerce"
    ).dt.date

    filtered = filtered[
        (filtered["call_date"] >= start_date)
        &
        (filtered["call_date"] <= end_date)
    ]

    # --------------------------------------------------------
    # KPI CARDS
    # --------------------------------------------------------

    st.divider()

    total_calls = len(filtered)

    connected = len(
        filtered[
            filtered["call_status"] == "Received"
        ]
    )

    high_interest = len(
        filtered[
            filtered["interest"].isin(
                ["Very Likely", "Extremely"]
            )
        ]
    )

    quotes = len(
        filtered[
            filtered["order_status"]
            == "Quote Requested"
        ]
    )

    orders = len(
        filtered[
            filtered["order_status"]
            == "Booked an Order"
        ]
    )

    col1, col2, col3, col4, col5 = st.columns(5)

    col1.metric(
        "📞 Calls",
        total_calls
    )

    col2.metric(
        "☎️ Connected",
        connected
    )

    col3.metric(
        "🔥 High Interest",
        high_interest
    )

    col4.metric(
        "💰 Quotes",
        quotes
    )

    col5.metric(
        "✅ Orders",
        orders
    )

