def get_clients():

    conn = get_connection()

    df = read_sql_query(
        "SELECT * FROM clients ORDER BY client_name",
        conn
    )

    conn.close()

    return df


def get_client(client_id):

    conn = get_connection()

    df = read_sql_query(
        "SELECT * FROM clients WHERE id = ?",
        conn,
        params=(client_id,)
    )

    conn.close()

    if len(df) == 0:
        return None

    return df.iloc[0]


def add_client(
    client_name,
    contact_number,
    address,
    area,
    city,
    email,
    client_type,
    client_label,
    next_followup_date,
    created_by
):

    conn = get_connection()

    cursor = conn.cursor()

    cursor.execute(adapt_sql("""
        INSERT INTO clients (
            client_name,
            contact_number,
            address,
            area,
            city,
            email,
            client_type,
            client_label,
            last_followup_date,
            next_followup_date,
            created_at,
            created_by
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """), (
        client_name,
        contact_number,
        address,
        area,
        city,
        email,
        client_type,
        client_label,
        None,
        str(next_followup_date) if next_followup_date else None,
        datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        created_by
    ))

    conn.commit()
    conn.close()


def get_call_count(client_id):

    conn = get_connection()

    cursor = conn.cursor()

    cursor.execute(adapt_sql("""
        SELECT COUNT(*)
        FROM call_history
        WHERE client_id = ?
    """), (client_id,))

    count = cursor.fetchone()[0]

    conn.close()

    return count


def add_call(
    client_id,
    call_status,
    interest,
    order_status,
    next_followup_date,
    next_followup_time,
    comments,
    called_by
):

    conn = get_connection()

    cursor = conn.cursor()

    # Existing call count
    cursor.execute(adapt_sql("""
        SELECT COUNT(*)
        FROM call_history
        WHERE client_id = ?
    """), (client_id,))

    call_number = cursor.fetchone()[0] + 1

    # Current call timestamp
    call_datetime = datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S"
    )

    cursor.execute(adapt_sql("""
        INSERT INTO call_history (
            client_id,
            call_datetime,
            call_status,
            interest,
            order_status,
            next_followup_date,
            next_followup_time,
            comments,
            called_by,
            call_number
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """), (
        client_id,
        call_datetime,
        call_status,
        interest,
        order_status,
        str(next_followup_date)
        if next_followup_date else None,
        str(next_followup_time)
        if next_followup_time else None,
        comments,
        called_by,
        call_number
    ))

    # Update client master record
    cursor.execute(adapt_sql("""
        UPDATE clients
        SET
            last_followup_date = ?,
            next_followup_date = ?
        WHERE id = ?
    """), (
        date.today().isoformat(),
        str(next_followup_date)
        if next_followup_date else None,
        client_id
    ))

    conn.commit()
    conn.close()


def get_call_history(client_id):

    conn = get_connection()

    df = read_sql_query("""
        SELECT
            call_number AS "Call #",
            call_datetime AS "Call Date & Time",
            call_status AS "Call Status",
            interest AS "Interest",
            order_status AS "Order Status",
            next_followup_date AS "Next Follow-up",
            next_followup_time AS "Time",
            comments AS "Comments",
            called_by AS "Called By"
        FROM call_history
        WHERE client_id = ?
        ORDER BY call_datetime DESC
    """, conn, params=(client_id,))

    conn.close()

    return df


