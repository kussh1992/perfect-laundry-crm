"""One-time copy of Perfect Laundry CRM SQLite data into PostgreSQL.

Usage (Windows PowerShell):
  $env:DATABASE_URL="postgresql://..."
  python migrate_sqlite_to_postgres.py --sqlite perfect_laundry_crm.db

This utility refuses to overwrite non-empty target tables unless --allow-existing is set.
"""
import argparse
import os
import sqlite3
import sys

import psycopg2

CLIENT_COLUMNS = [
    "id", "client_name", "contact_number", "address", "area", "city", "email",
    "client_type", "client_label", "last_followup_date", "next_followup_date",
    "created_at", "created_by"
]
CALL_COLUMNS = [
    "id", "client_id", "call_datetime", "call_status", "interest", "order_status",
    "next_followup_date", "next_followup_time", "comments", "called_by", "call_number"
]


def get_database_url():
    url = os.getenv("DATABASE_URL", "").strip()
    if not url:
        print("ERROR: Set DATABASE_URL to your PostgreSQL connection string first.", file=sys.stderr)
        sys.exit(2)
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://"):]
    return url


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--sqlite", default="perfect_laundry_crm.db", help="Path to the original SQLite database")
    parser.add_argument("--allow-existing", action="store_true", help="Allow inserting into non-empty target tables; duplicate IDs may fail")
    args = parser.parse_args()

    if not os.path.isfile(args.sqlite):
        print(f"ERROR: SQLite file not found: {args.sqlite}", file=sys.stderr)
        sys.exit(2)

    source = sqlite3.connect(args.sqlite)
    source.row_factory = sqlite3.Row
    target = psycopg2.connect(get_database_url())
    try:
        with target:
            with target.cursor() as cur:
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS clients (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        client_name TEXT NOT NULL, contact_number TEXT, address TEXT, area TEXT,
                        city TEXT, email TEXT, client_type TEXT, client_label TEXT,
                        last_followup_date TEXT, next_followup_date TEXT, created_at TEXT, created_by TEXT
                    )
                """)
                cur.execute("""
                    CREATE TABLE IF NOT EXISTS call_history (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        client_id BIGINT REFERENCES clients(id), call_datetime TEXT, call_status TEXT,
                        interest TEXT, order_status TEXT, next_followup_date TEXT, next_followup_time TEXT,
                        comments TEXT, called_by TEXT, call_number INTEGER
                    )
                """)
                cur.execute("SELECT COUNT(*) FROM clients")
                target_clients = cur.fetchone()[0]
                cur.execute("SELECT COUNT(*) FROM call_history")
                target_calls = cur.fetchone()[0]
                if (target_clients or target_calls) and not args.allow_existing:
                    raise RuntimeError(
                        f"Target is not empty (clients={target_clients}, call_history={target_calls}). "
                        "No data was inserted. Use --allow-existing only if you have reviewed the target."
                    )
                clients = source.execute("SELECT * FROM clients ORDER BY id").fetchall()
                calls = source.execute("SELECT * FROM call_history ORDER BY id").fetchall()
                client_sql = "INSERT INTO clients (" + ",".join(CLIENT_COLUMNS) + ") VALUES (" + ",".join(["%s"]*len(CLIENT_COLUMNS)) + ")"
                call_sql = "INSERT INTO call_history (" + ",".join(CALL_COLUMNS) + ") VALUES (" + ",".join(["%s"]*len(CALL_COLUMNS)) + ")"
                for row in clients:
                    cur.execute(client_sql, tuple(row[col] for col in CLIENT_COLUMNS))
                for row in calls:
                    cur.execute(call_sql, tuple(row[col] for col in CALL_COLUMNS))
                # Reset identity sequences to the maximum copied IDs.
                cur.execute("SELECT setval(pg_get_serial_sequence('clients','id'), COALESCE((SELECT MAX(id) FROM clients), 1), EXISTS(SELECT 1 FROM clients))")
                cur.execute("SELECT setval(pg_get_serial_sequence('call_history','id'), COALESCE((SELECT MAX(id) FROM call_history), 1), EXISTS(SELECT 1 FROM call_history))")
                cur.execute("SELECT COUNT(*) FROM clients")
                final_clients = cur.fetchone()[0]
                cur.execute("SELECT COUNT(*) FROM call_history")
                final_calls = cur.fetchone()[0]
        print("Migration completed successfully.")
        print(f"SQLite source: clients={len(clients)}, call_history={len(calls)}")
        print(f"PostgreSQL target: clients={final_clients}, call_history={final_calls}")
        if final_clients < len(clients) or final_calls < len(calls):
            print("WARNING: Target counts are lower than source counts; investigate before using the app.", file=sys.stderr)
    finally:
        source.close()
        target.close()

if __name__ == "__main__":
    main()
